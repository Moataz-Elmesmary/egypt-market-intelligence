"""Embed brand logos in the custom visual as data URIs (original + all-white variant).

Sources: Wikimedia Commons PD-textlogo files (talabat, instashop, Pepsi, Coca-Cola, Big Cola) and the
companies' own site assets (Breadfast, elmenus, Rabbit). Logos are trademarks of their owners and are
used only to identify the companies in an independent analysis.
"""
import base64
import io
import json
import re
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw" / "logos"
FILES = {"talabat": "talabat.svg", "instashop": "instashop.svg", "Pepsi": "pepsi.svg", "Coca-Cola": "cocacola.svg",
         "Big Cola": "bigcola.svg", "Breadfast": "breadfast.svg", "elmenus": "elmenus.svg", "Rabbit": "rabbit.png"}


def clean_svg(s):
    s = re.sub(r"<\?xml.*?\?>|<!DOCTYPE.*?>|<!--.*?-->", "", s, flags=re.S).strip()
    head = re.search(r"<svg\b[^>]*>", s).group(0)
    if "viewBox" not in head:
        w = float(re.search(r'width="([\d.]+)', head).group(1)); h = float(re.search(r'height="([\d.]+)', head).group(1))
        s = s.replace(head, head[:-1] + f' viewBox="0 0 {w} {h}">', 1)
    return s


def white(s):
    s = re.sub(r'fill="(?!none)[^"]*"', 'fill="#FFFFFF"', s)
    s = re.sub(r"fill:\s*(?!none)[^;}\"]+", "fill:#FFFFFF", s)
    s = re.sub(r'stop-color="[^"]*"', 'stop-color="#FFFFFF"', s)
    return s


def uri(data, mime):
    return f"data:{mime};base64," + base64.b64encode(data).decode()


out = {}
for brand, f in FILES.items():
    p = RAW / f
    if f.endswith(".svg"):
        s = clean_svg(p.read_text(encoding="utf-8"))
        out[brand] = {"color": uri(s.encode(), "image/svg+xml"), "white": uri(white(s).encode(), "image/svg+xml")}
    else:
        im = Image.open(p).convert("RGBA")
        im.thumbnail((480, 480))
        b = io.BytesIO(); im.save(b, "PNG", optimize=True)
        w = Image.new("RGBA", im.size, (255, 255, 255, 0)); w.putalpha(im.getchannel("A"))
        wb = io.BytesIO(); Image.merge("RGBA", (*Image.new("RGB", im.size, (255, 255, 255)).split(), im.getchannel("A"))).save(wb, "PNG", optimize=True)
        out[brand] = {"color": uri(b.getvalue(), "image/png"), "white": uri(wb.getvalue(), "image/png")}
ts = "// Brand logos as data URIs, generated by egypt/make_logos.py. Trademarks of their owners; used to identify companies.\n"
ts += "export const LOGOS: Record<string, { color: string; white: string }> = " + json.dumps(out) + ";\n"
(HERE / "visual" / "src" / "logos.ts").write_text(ts, encoding="utf-8")
print({k: len(v["color"]) for k, v in out.items()}, "total KB", round(len(ts) / 1024))
